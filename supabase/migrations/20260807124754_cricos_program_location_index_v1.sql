do update set institution_id = excluded.institution_id, source_url = excluded.source_url;

create table if not exists ingest.cricos_locations_au (
  id bigint generated by default as identity primary key,
  source_row_id integer,
  provider_code text not null,
  institution_name text not null,
  location_name text not null,
  location_type text,
  address_line_1 text,
  address_line_2 text,
  address_line_3 text,
  address_line_4 text,
  city text,
  state text,
  postcode text,
  source_resource_id text not null,
  source_last_modified timestamptz not null,
  synced_at timestamptz not null default now()
);

create unique index if not exists cricos_locations_au_identity_uidx
  on ingest.cricos_locations_au(provider_code, location_name, coalesce(city, ''), coalesce(state, ''), coalesce(postcode, ''));
create index if not exists cricos_locations_au_provider_idx
  on ingest.cricos_locations_au(provider_code, state, city, postcode);

