-- Official CRICOS provider/location foundation for city-aware programme search.

insert into catalog.institution_identifiers (institution_id, identifier_system, identifier_value, source_url)
select distinct
  i.id,
  'AU_CRICOS_PROVIDER_CODE',
  c.cricos_code,
  'https://cricos.education.gov.au/institution/InstitutionSearch.aspx'
from catalog.institutions i
join catalog.institution_identifiers legacy
  on legacy.institution_id = i.id
 and legacy.identifier_system = 'AU_PROVIDER_ID'
join ingest.courses_au c
  on c.institution_id = legacy.identifier_value
where i.country_code = 'AU'
  and c.cricos_code is not null
  and btrim(c.cricos_code) <> ''
on conflict (identifier_system, identifier_value)
do update set institution_id = excluded.institution_id, source_url = excluded.source_url;

